export type I18nKey = keyof typeof MESSAGES.zh;

export function tr(lang: AppLanguage, key: I18nKey): string {
  if (lang === 'zht') {
    return toTraditionalTaiwan(zhMessages[key]);
  }
  const packKey = LANG_MESSAGES_KEY[lang];
  const pack = MESSAGES[packKey];
  return pack[key] ?? zhMessages[key];
}

export function monthChipLabel(lang: AppLanguage, month: number): string {
  if (lang === 'zh' || lang === 'zht' || lang === 'ja') return `${month}月`;
  if (lang === 'ko') return `${month}월`;
  return EN_MONTHS[month - 1] ?? String(month);
}
